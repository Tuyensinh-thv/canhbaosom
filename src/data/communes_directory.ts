export function removeVietnameseTones(str: string): string {
  if (!str) return '';
  let s = str.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  s = s.replace(/[đĐ]/g, 'd');
  return s.toLowerCase().trim();
}

